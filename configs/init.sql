-- Object-level ACLs. Unlike bucket_acls these are keyed by object
-- (bucket_id + obj_name_hash + object_name), so an object can carry its own
-- canned ACL (e.g. public-read) independent of the bucket. The object ACL
-- overrides the bucket ACL for object-level operations (GetObject/HeadObject).
CREATE TABLE IF NOT EXISTS object_acls
(
    id            BIGINT        NOT NULL COMMENT 'ACL entry unique id (generated by GenerateID)',
    bucket_id     BIGINT        NOT NULL COMMENT 'bucket id',
    obj_name_hash DECIMAL(39,0) NOT NULL COMMENT 'hash of object name',
    object_name   VARCHAR(1024) NOT NULL COMMENT 'object name',
    version       VARCHAR(36)   NOT NULL DEFAULT '' COMMENT 'object version (empty for unversioned)',
    grantee       VARCHAR(256)  NOT NULL COMMENT 'grantee identifier: user ID for canonical_user, or URI for AllUsers/AuthenticatedUsers',
    grantee_type  VARCHAR(32)   NOT NULL COMMENT 'grantee type: canonical_user | all_users | authenticated_users',
    permission    VARCHAR(32)   NOT NULL COMMENT 'S3 permission: FULL_CONTROL | WRITE | READ | READ_ACP | WRITE_ACP',
    created_at    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    INDEX index_object_acls_bucket_obj (bucket_id, obj_name_hash, version)
);

