CREATE TABLE IF NOT EXISTS users
(
    id                   BIGINT NOT NULL COMMENT 'user unique id (generated by GenerateID)',
    name                 VARCHAR(128) NOT NULL COMMENT 'user name (unique)',
    password             VARCHAR(256) NOT NULL COMMENT 'hashed password',
    email                VARCHAR(256) NOT NULL DEFAULT '' COMMENT 'user email (unique, case-insensitive)',
    accesskey            VARCHAR(64)  NOT NULL COMMENT 'access key for API',
    secretkey            VARCHAR(64)  NOT NULL COMMENT 'secret key for API',
    mfa_secret           VARCHAR(512)          DEFAULT ''  COMMENT 'encrypted TOTP secret (AES-256-GCM)',
    mfa_enabled          BOOLEAN      NOT NULL DEFAULT '0' COMMENT 'MFA enabled flag',
    urole                VARCHAR(32)  NOT NULL COMMENT 'user role: user / group_admin / super_admin',
    group_id             BIGINT       NOT NULL COMMENT 'associated group id',
    must_change_password BOOLEAN      NOT NULL DEFAULT '0' COMMENT 'must change password on next login',
    bypass               BOOLEAN      NOT NULL DEFAULT '0' COMMENT 'IAM s3:BypassGovernanceRetention',
    path                 VARCHAR(512) NOT NULL DEFAULT '/' COMMENT 'IAM user path (ARN component)',
    account_id           VARCHAR(64)  NOT NULL DEFAULT '000000000000' COMMENT 'IAM account id; DEFAULT = default account literal value',
    is_account_root      TINYINT      NOT NULL DEFAULT '0' COMMENT 'IAM account root marker (never inferred from super_admin)',
    identity_type        VARCHAR(16)  NOT NULL DEFAULT 'legacy' COMMENT 'identity kind: legacy (StoreFS admin/user) | iam (AWS IAM principal)',
    created_at           DATETIME              DEFAULT CURRENT_TIMESTAMP COMMENT 'create time',
    PRIMARY KEY (id),
    INDEX index_users_group_id (group_id),
    INDEX index_users_name (name),
    INDEX index_users_accesskey (accesskey),
    INDEX index_users_urole (urole)
);

