CREATE TABLE IF NOT EXISTS policies
(
    id            BIGINT       NOT NULL,
    name          VARCHAR(128) NOT NULL,
    type          VARCHAR(16)  NOT NULL,
    replicas      INT,
    data_shards   INT,
